#!/usr/bin/env python3
"""Generates RenyiFullLHKappaData.lean: rational enclosures of the five q_s-powers behind the cubic
Hermite minorant kappa of K at the nodes 3/20, 17/20 (lem:fqe-large-head-dual, (LH1)) and the proof
that kappa_i <= c_i (the Hermite coefficients) coefficientwise.
Run: python3 gen_lh_kappa.py > RenyiFullLHKappaData.lean"""
from fractions import Fraction as F
from mpmath import mp, mpf, power
import sympy as s

mp.dps = 60
Q1587 = F(1587, 1000)
DEN = 10**13
BASES = [F(13, 10), F(17, 20), F(27, 10), F(3, 20), F(3)]
NAMES = ['p13', 'p17', 'p27', 'p3', 'p3b']
KAPPA = [F(5238033, 10**7), F(142244, 10**7), F(4204281, 10**7), F(384307, 10**7)]

def bounds(x):
    t = power(mpf(x.numerator) / x.denominator, mpf(1587) / 1000)
    lo = F(int(mp.floor(t * DEN)), DEN) - F(1, DEN)
    hi = F(int(mp.ceil(t * DEN)), DEN) + F(1, DEN)
    assert lo ** 1000 <= x ** 1587 <= hi ** 1000
    return lo, hi

def lit(f):
    f = F(f)
    return f"({f.numerator} / {f.denominator} : ℝ)" if f.denominator != 1 else f"({f.numerator} : ℝ)"

def litQ(f):
    f = F(f)
    return f"({f.numerator} / {f.denominator} : ℚ)" if f.denominator != 1 else f"({f.numerator} : ℚ)"

l = F(3, 20); u = F(17, 20)
M = s.Matrix([[1, s.Rational(l.numerator, l.denominator), s.Rational(l.numerator, l.denominator)**2, s.Rational(l.numerator, l.denominator)**3],
              [0, 1, 2*s.Rational(l.numerator, l.denominator), 3*s.Rational(l.numerator, l.denominator)**2],
              [1, s.Rational(u.numerator, u.denominator), s.Rational(u.numerator, u.denominator)**2, s.Rational(u.numerator, u.denominator)**3],
              [0, 1, 2*s.Rational(u.numerator, u.denominator), 3*s.Rational(u.numerator, u.denominator)**2]])
Minv = M.inv()

def spow(x, n=1): return x

def main():
    enc = {}
    out = []
    out.append("""module

public import FormalResearch.FourQubitEntropy.RenyiFullLHMono

/-!
# The cubic Hermite minorant `κ` of `K` at the nodes `3/20, 17/20` (generated by `gen_lh_kappa.py`)

`(LH1)` of `lem:fqe-large-head-dual`: `K(z) ≥ κ(z) = κ₀ + κ₁ z + κ₂ z² + κ₃ z³` on `[0,1]`, where
`κ_i` is a rational lower rounding of the Hermite coefficient `c_i`.  The coefficients `c_i` are rational
linear combinations of `K(l), K'(l), K(u), K'(u)`; their enclosures come from rational enclosures of the five
powers `x^{q_s}`, `x ∈ {13/10, 17/20, 27/10, 3/20, 3}`.
-/

@[expose] public section

namespace FormalResearch.FourQubitEntropy.RenyiFull

open Set
""")
    for x, nm in zip(BASES, NAMES):
        lo, hi = bounds(x)
        enc[nm] = (lo, hi)
        out.append(f"""theorem {nm}_lo : {lit(lo)} ≤ ({lit(x)}) ^ qS := by
  have := le_rpow_qS_Q (x := {litQ(x)}) (b := {litQ(lo)}) (by norm_num) (by norm_num) (by decide +kernel)
  simpa using this

theorem {nm}_hi : ({lit(x)}) ^ qS ≤ {lit(hi)} := by
  have := rpow_qS_le_Q (x := {litQ(x)}) (b := {litQ(hi)}) (by norm_num) (by norm_num) (by decide +kernel)
  simpa using this
""")
    q = F(1587, 1000)
    (a_lo, a_hi), (b_lo, b_hi), (c_lo, c_hi), (d_lo, d_hi), (t_lo, t_hi) = [enc[n] for n in NAMES]
    # data enclosures (X = numerator pieces, T = 3^q)
    Kl = ((a_lo + 2*b_lo)/t_hi, (a_hi + 2*b_hi)/t_lo)
    Ku = ((c_lo + 2*d_lo)/t_hi, (c_hi + 2*d_hi)/t_lo)
    Xl = (2*(a_lo/F(13, 10) - b_hi/F(17, 20)), 2*(a_hi/F(13, 10) - b_lo/F(17, 20)))
    Xu = (2*(c_lo/F(27, 10) - d_hi/F(3, 20)), 2*(c_hi/F(27, 10) - d_lo/F(3, 20)))
    K1l = (q*Xl[0]/t_hi, q*Xl[1]/t_lo)
    K1u = (q*Xu[0]/t_hi, q*Xu[1]/t_lo)
    assert Xl[0] > 0 and Xu[0] > 0
    data = [Kl, K1l, Ku, K1u]
    # coefficient enclosures
    cl = []
    for i in range(4):
        w = [F(int(Minv[i, j].p), int(Minv[i, j].q)) for j in range(4)]
        lo = sum(wj*(d[0] if wj > 0 else d[1]) for wj, d in zip(w, data))
        hi = sum(wj*(d[1] if wj > 0 else d[0]) for wj, d in zip(w, data))
        assert KAPPA[i] <= lo, (i, float(KAPPA[i]), float(lo))
        cl.append(w)
    out.append(f"""
theorem kfun_l_enc : {lit(Kl[0])} ≤ kfun qS (3 / 20) ∧ kfun qS (3 / 20) ≤ {lit(Kl[1])} := by
  have h1 := p13_lo; have h2 := p13_hi; have h3 := p17_lo; have h4 := p17_hi
  have h5 := p3b_lo; have h6 := p3b_hi
  have e1 : (1 + 2 * (3 / 20 : ℝ)) = 13 / 10 := by norm_num
  have e2 : (1 - (3 / 20 : ℝ)) = 17 / 20 := by norm_num
  unfold kfun
  rw [e1, e2]
  have hp : (0 : ℝ) < 3 ^ qS := by linarith
  constructor
  · rw [le_div_iff₀ hp]; nlinarith
  · rw [div_le_iff₀ hp]; nlinarith

theorem kfun_u_enc : {lit(Ku[0])} ≤ kfun qS (17 / 20) ∧ kfun qS (17 / 20) ≤ {lit(Ku[1])} := by
  have h1 := p27_lo; have h2 := p27_hi; have h3 := p3_lo; have h4 := p3_hi
  have h5 := p3b_lo; have h6 := p3b_hi
  have e1 : (1 + 2 * (17 / 20 : ℝ)) = 27 / 10 := by norm_num
  have e2 : (1 - (17 / 20 : ℝ)) = 3 / 20 := by norm_num
  unfold kfun
  rw [e1, e2]
  have hp : (0 : ℝ) < 3 ^ qS := by linarith
  constructor
  · rw [le_div_iff₀ hp]; nlinarith
  · rw [div_le_iff₀ hp]; nlinarith

theorem mul_div_enc {{q T X Xlo Xhi Tlo Thi : ℝ}} (hq : 0 ≤ q) (hTlo : 0 < Tlo) (h1 : Tlo ≤ T) (h2 : T ≤ Thi)
    (hX0 : 0 ≤ Xlo) (h3 : Xlo ≤ X) (h4 : X ≤ Xhi) :
    q * Xlo / Thi ≤ q / T * X ∧ q / T * X ≤ q * Xhi / Tlo := by
  have hT : 0 < T := by linarith
  have hThi : 0 < Thi := by linarith
  constructor
  · have e : q * Xlo / Thi = q / Thi * Xlo := by ring
    rw [e]
    exact mul_le_mul (div_le_div_of_nonneg_left hq hT h2) h3 hX0 (by positivity)
  · have e : q * Xhi / Tlo = q / Tlo * Xhi := by ring
    rw [e]
    exact mul_le_mul (div_le_div_of_nonneg_left hq hTlo h1) h4 (by linarith) (by positivity)

theorem kf1_l_enc : {lit(K1l[0])} ≤ kf1 qS (3 / 20) ∧ kf1 qS (3 / 20) ≤ {lit(K1l[1])} := by
  have h1 := p13_lo; have h2 := p13_hi; have h3 := p17_lo; have h4 := p17_hi
  have h5 := p3b_lo; have h6 := p3b_hi
  have e1 : (1 + 2 * (3 / 20 : ℝ)) = 13 / 10 := by norm_num
  have e2 : (1 - (3 / 20 : ℝ)) = 17 / 20 := by norm_num
  have r1 : ((13 / 10 : ℝ)) ^ (qS - 1) = ((13 / 10 : ℝ)) ^ qS / (13 / 10) := Real.rpow_sub_one (by norm_num) qS
  have r2 : ((17 / 20 : ℝ)) ^ (qS - 1) = ((17 / 20 : ℝ)) ^ qS / (17 / 20) := Real.rpow_sub_one (by norm_num) qS
  unfold kf1
  rw [e1, e2, r1, r2]
  have := mul_div_enc (q := qS) (T := 3 ^ qS) (X := 2 * (((13 / 10 : ℝ)) ^ qS / (13 / 10)) - 2 * (((17 / 20 : ℝ)) ^ qS / (17 / 20)))
    (Xlo := {lit(Xl[0])}) (Xhi := {lit(Xl[1])}) (Tlo := {lit(t_lo)}) (Thi := {lit(t_hi)})
    (by unfold qS; norm_num) (by norm_num) h5 h6 (by norm_num) (by linarith) (by linarith)
  unfold qS at this ⊢
  constructor
  · refine le_trans (le_of_eq ?_) this.1; norm_num
  · refine le_trans this.2 (le_of_eq ?_); norm_num

theorem kf1_u_enc : {lit(K1u[0])} ≤ kf1 qS (17 / 20) ∧ kf1 qS (17 / 20) ≤ {lit(K1u[1])} := by
  have h1 := p27_lo; have h2 := p27_hi; have h3 := p3_lo; have h4 := p3_hi
  have h5 := p3b_lo; have h6 := p3b_hi
  have e1 : (1 + 2 * (17 / 20 : ℝ)) = 27 / 10 := by norm_num
  have e2 : (1 - (17 / 20 : ℝ)) = 3 / 20 := by norm_num
  have r1 : ((27 / 10 : ℝ)) ^ (qS - 1) = ((27 / 10 : ℝ)) ^ qS / (27 / 10) := Real.rpow_sub_one (by norm_num) qS
  have r2 : ((3 / 20 : ℝ)) ^ (qS - 1) = ((3 / 20 : ℝ)) ^ qS / (3 / 20) := Real.rpow_sub_one (by norm_num) qS
  unfold kf1
  rw [e1, e2, r1, r2]
  have := mul_div_enc (q := qS) (T := 3 ^ qS) (X := 2 * (((27 / 10 : ℝ)) ^ qS / (27 / 10)) - 2 * (((3 / 20 : ℝ)) ^ qS / (3 / 20)))
    (Xlo := {lit(Xu[0])}) (Xhi := {lit(Xu[1])}) (Tlo := {lit(t_lo)}) (Thi := {lit(t_hi)})
    (by unfold qS; norm_num) (by norm_num) h5 h6 (by norm_num) (by linarith) (by linarith)
  unfold qS at this ⊢
  constructor
  · refine le_trans (le_of_eq ?_) this.1; norm_num
  · refine le_trans this.2 (le_of_eq ?_); norm_num
""")
    # coefficient definitions and identities
    for i in range(4):
        w = cl[i]
        out.append(f"""noncomputable def hc{i} (Kl K1l Ku K1u : ℝ) : ℝ :=
  {lit(w[0])} * Kl + {lit(w[1])} * K1l + {lit(w[2])} * Ku + {lit(w[3])} * K1u
""")
    out.append("""theorem hc_at_l (Kl K1l Ku K1u : ℝ) :
    hc0 Kl K1l Ku K1u + hc1 Kl K1l Ku K1u * (3 / 20) + hc2 Kl K1l Ku K1u * (3 / 20) ^ 2 +
      hc3 Kl K1l Ku K1u * (3 / 20) ^ 3 = Kl := by
  unfold hc0 hc1 hc2 hc3; ring

theorem hc_d_at_l (Kl K1l Ku K1u : ℝ) :
    hc1 Kl K1l Ku K1u + 2 * hc2 Kl K1l Ku K1u * (3 / 20) + 3 * hc3 Kl K1l Ku K1u * (3 / 20) ^ 2 = K1l := by
  unfold hc1 hc2 hc3; ring

theorem hc_at_u (Kl K1l Ku K1u : ℝ) :
    hc0 Kl K1l Ku K1u + hc1 Kl K1l Ku K1u * (17 / 20) + hc2 Kl K1l Ku K1u * (17 / 20) ^ 2 +
      hc3 Kl K1l Ku K1u * (17 / 20) ^ 3 = Ku := by
  unfold hc0 hc1 hc2 hc3; ring

theorem hc_d_at_u (Kl K1l Ku K1u : ℝ) :
    hc1 Kl K1l Ku K1u + 2 * hc2 Kl K1l Ku K1u * (17 / 20) + 3 * hc3 Kl K1l Ku K1u * (17 / 20) ^ 2 = K1u := by
  unfold hc1 hc2 hc3; ring
""")
    k = [lit(x) for x in KAPPA]
    out.append(f"""/-- The rational minorant `κ` (7-digit lower roundings of the Hermite coefficients). -/
noncomputable def kap (z : ℝ) : ℝ :=
  {k[0]} + {k[1]} * z + {k[2]} * z ^ 2 + {k[3]} * z ^ 3

theorem kap_le_hc {{z : ℝ}} (hz0 : 0 ≤ z) :
    kap z ≤ hc0 (kfun qS (3 / 20)) (kf1 qS (3 / 20)) (kfun qS (17 / 20)) (kf1 qS (17 / 20)) +
      hc1 (kfun qS (3 / 20)) (kf1 qS (3 / 20)) (kfun qS (17 / 20)) (kf1 qS (17 / 20)) * z +
      hc2 (kfun qS (3 / 20)) (kf1 qS (3 / 20)) (kfun qS (17 / 20)) (kf1 qS (17 / 20)) * z ^ 2 +
      hc3 (kfun qS (3 / 20)) (kf1 qS (3 / 20)) (kfun qS (17 / 20)) (kf1 qS (17 / 20)) * z ^ 3 := by
  have a := kfun_l_enc; have b := kf1_l_enc; have c := kfun_u_enc; have d := kf1_u_enc
  unfold kap hc0 hc1 hc2 hc3
  have z2 := pow_nonneg hz0 2
  have z3 := pow_nonneg hz0 3
  have h0 : {k[0]} ≤ {lit(cl[0][0])} * kfun qS (3 / 20) + {lit(cl[0][1])} * kf1 qS (3 / 20) + {lit(cl[0][2])} * kfun qS (17 / 20) + {lit(cl[0][3])} * kf1 qS (17 / 20) := by
    linarith [a.1, a.2, b.1, b.2, c.1, c.2, d.1, d.2]
  have h1 : {k[1]} ≤ {lit(cl[1][0])} * kfun qS (3 / 20) + {lit(cl[1][1])} * kf1 qS (3 / 20) + {lit(cl[1][2])} * kfun qS (17 / 20) + {lit(cl[1][3])} * kf1 qS (17 / 20) := by
    linarith [a.1, a.2, b.1, b.2, c.1, c.2, d.1, d.2]
  have h2 : {k[2]} ≤ {lit(cl[2][0])} * kfun qS (3 / 20) + {lit(cl[2][1])} * kf1 qS (3 / 20) + {lit(cl[2][2])} * kfun qS (17 / 20) + {lit(cl[2][3])} * kf1 qS (17 / 20) := by
    linarith [a.1, a.2, b.1, b.2, c.1, c.2, d.1, d.2]
  have h3 : {k[3]} ≤ {lit(cl[3][0])} * kfun qS (3 / 20) + {lit(cl[3][1])} * kf1 qS (3 / 20) + {lit(cl[3][2])} * kfun qS (17 / 20) + {lit(cl[3][3])} * kf1 qS (17 / 20) := by
    linarith [a.1, a.2, b.1, b.2, c.1, c.2, d.1, d.2]
  nlinarith [mul_nonneg hz0 (sub_nonneg.2 h1), mul_nonneg z2 (sub_nonneg.2 h2), mul_nonneg z3 (sub_nonneg.2 h3)]

end FormalResearch.FourQubitEntropy.RenyiFull""")
    print("\n".join(out))
    return enc

if __name__ == '__main__':
    main()
