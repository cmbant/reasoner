def aq(n, s, j):
    return F(comb(n - j, s - j), 2 ** s * comb(n, s)) if j <= s else F(0)


def shq(n, i, j):
    # coefficient of x^(n-i) y^i in ((x+3y)/2)^(n-j) ((y-x)/2)^j, via expansion of (x+3y)^(n-j) (y-x)^j
    tot = 0
    for r in range(0, i + 1):  # r y's from the first factor, i-r from the second
        q = i - r
        if r > n - j or q > j:
            continue
        tot += comb(n - j, r) * 3 ** r * comb(j, q) * (-1) ** (j - q)
    return F(tot, 2 ** n)


def residual(n, L, es, ys):
    k = n // 2
    return [aq(n, k, j) - (L if j == 0 else 0)
            - sum(e * (aq(n, s, j) - aq(n, n - s, j)) for s, e in es.items())
            - sum(y * shq(n, i, j) for i, y in ys.items()) for j in range(n + 1)]


def lit(q):
    q = F(q)
    if q.denominator == 1:
        return f"({q.numerator} : ℚ)" if q >= 0 else f"(-{-q.numerator} : ℚ)"
    return f"({q.numerator} / {q.denominator} : ℚ)" if q >= 0 else f"(-{-q.numerator} / {q.denominator} : ℚ)"


def plist(d):
    return "[" + ", ".join(f"({i}, {lit(F(v))})" for i, v in sorted(d.items())) + "]"


