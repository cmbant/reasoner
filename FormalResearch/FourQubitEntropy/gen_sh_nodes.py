#!/usr/bin/env python3
"""Generates RenyiFullSHNodes.lean: numerical node bounds A_q(u_i) >= a_i and binH(1/3) bound
for lem:fqe-small-head-dual (q_s = 1587/1000).  Run: python3 gen_sh_nodes.py > RenyiFullSHNodes.lean"""
from fractions import Fraction as F
from mpmath import mp, mpf, power
import math
mp.dps = 60
Q = F(1587, 1000); R = Q - 1
NODES = [(F(1,100), F(217,1000)), (F(3,100), F(289,1000)), (F(1,20), F(332,1000)), (F(2,25), F(377,1000)),
         (F(13,100), F(43,100)), (F(39,200), F(48,100)), (F(47,200), F(505,1000))]
DEN = 10**8

def lo_pow(x):
    """rational b <= x^q with b^1000 <= x^1587 exact"""
    t = power(mpf(x.numerator)/x.denominator, mpf(1587)/1000)
    b = F(int(mp.floor(t*DEN)), DEN) - F(1, DEN)
    assert b > 0 and b**1000 <= x**1587
    return b

def lit(f):
    return f"({f.numerator} / {f.denominator} : ℚ)" if f.denominator != 1 else f"({f.numerator} : ℚ)"

def taylor6(y):
    return sum(y**k / math.factorial(k) for k in range(7))

def node(name, u, tau, goal, post):
    v = 1 - u
    b1, b2 = lo_pow(u), lo_pow(v)
    S = b1 + b2
    L_lo = F(693147, 10**6)
    y = F(int(R * tau * L_lo * DEN), DEN)
    assert y <= R * tau * L_lo and y >= 0
    assert S * taylor6(y) >= 1, (name, float(S * taylor6(y)))
    print(f"""
theorem {name} : {goal} := by
  {post}
  have e1 : (({b1.numerator} / {b1.denominator} : ℚ) : ℝ) ≤ (({u.numerator} / {u.denominator} : ℚ) : ℝ) ^ qS :=
    le_rpow_qS_Q (by norm_num) (by norm_num) (by decide +kernel)
  have e2 : (({b2.numerator} / {b2.denominator} : ℚ) : ℝ) ≤ (({v.numerator} / {v.denominator} : ℚ) : ℝ) ^ qS :=
    le_rpow_qS_Q (by norm_num) (by norm_num) (by decide +kernel)
  push_cast at e1 e2
  have hS : (({b1.numerator} / {b1.denominator} : ℝ) + {b2.numerator} / {b2.denominator}) ≤
      (1 - ({u.numerator} / {u.denominator} : ℝ)) ^ qS + ({u.numerator} / {u.denominator} : ℝ) ^ qS := by
    have : (1 - ({u.numerator} / {u.denominator} : ℝ)) = {v.numerator} / {v.denominator} := by norm_num
    rw [this]; linarith
  have hqS : qS - 1 = 587 / 1000 := by unfold qS; norm_num
  refine le_of_le_of_eq (binH_le_of_exp (u := ({u.numerator} / {u.denominator} : ℝ))
    (S' := {b1.numerator} / {b1.denominator} + {b2.numerator} / {b2.denominator})
    (y := {y.numerator} / {y.denominator}) (τ := {tau.numerator} / {tau.denominator})
    (by norm_num) (by norm_num) (by norm_num) hS (by norm_num) (by rw [hqS]; norm_num) (by norm_num)) ?_
  norm_num
""")

print("""import FormalResearch.FourQubitEntropy.RenyiFullSHD

/-!
# Small-head dual: node values of `A_q` (generated by `gen_sh_nodes.py`)

`a_i ≤ A_q(u_i)` at `q = q_s` for the staircase nodes `u_i`, and `H_q(1/3, 2/3) ≤ 1751/2000`.
Each is an integer-power rpow comparison plus a Taylor bound of the exponential (`binH_le_of_exp`).
-/

namespace FormalResearch.FourQubitEntropy.RenyiFull
""")
for i, (u, a) in enumerate(NODES):
    d = u * (1 - u)
    tau = 4 * d - a * d * (1 - 2*u)**2
    node(f"sh_node_{i}", u, tau, f"({a.numerator} / {a.denominator} : ℝ) ≤ bqA ({u.numerator} / {u.denominator})",
         "refine bqA_ge_of_binH (by norm_num) (by norm_num) ?_")
u = F(1, 3); tau = F(1751, 2000)
node("binH_third_le", u, tau, f"binH qBQ (1 / 3) ≤ 1751 / 2000", "")
print("\nend FormalResearch.FourQubitEntropy.RenyiFull")
