"""Generate RenyiFullCCCells.lean: the two Bernstein certificates of the moment case of lem:fqe-capped-cubic (Paper E).

  curvature cell: on 0 <= x <= 17/100, |v| <= 6/25,  N^2 + N N_xx - N_x^2 <= 0  (bidegree (4,4), one box), where
       N = 1 + x V + x^2 W, V = A + B v + C v^2, W = C/4 + T v   (A,B,C,T: order q_s = 1587/1000 coefficients of
       lem:fqe-near-uniform-moment);  hence (ln N)_xx <= -1.
  endpoint cell: at x = X = 17/100, the eight-term Taylor minorant of ln(1+z), z = X (V + X W), satisfies
       sum_{j<=8} (-1)^(j+1) z^j / j  >=  r L+ X (171/40 - (8/3) v - (11/10) X)   for |v| <= 6/25
       (L+ = 6931471808/10^10 > ln 2, r = q_s - 1); univariate, degree 16, two Bernstein boxes.

Run from anywhere: python3 gen_cc_cells.py (writes RenyiFullCCCells.lean next to this file)."""
import os
from math import comb
import sympy as sp
from sympy import Rational as R

x, v, s, w = sp.symbols('x v s w')
q = R(1587, 1000)
r = q - 1
A = 2*q*r
B = R(8, 3)*q*r*(q-2)
C = R(8, 3)*q*r*(q-2)*(q-3)
T = R(2, 3)*(q-4)*C
X = R(17, 100)
Lp = R(6931471808, 10**10)
K = r*Lp


def lit(c):
    c = R(c)
    if c < 0:
        return f"(-({-c.p} / {c.q}) : ℝ)" if c.q != 1 else f"(-({-c.p}) : ℝ)"
    return f"({c.p} / {c.q} : ℝ)" if c.q != 1 else f"({c.p} : ℝ)"


V = A + B*v + C*v**2
W = C/4 + T*v
N = 1 + x*V + x**2*W
E = sp.expand(-(N**2 + N*sp.diff(N, x, 2) - sp.diff(N, x)**2))
Pe = sp.Poly(sp.expand(E.subs({x: X*s, v: -R(6, 25)+R(12, 25)*w})), s, w)
co = Pe.as_dict()
n1, n2 = Pe.degree(s), Pe.degree(w)
assert (n1, n2) == (4, 4)
terms = []
for a in range(n1+1):
    for b in range(n2+1):
        val = sum(c*R(comb(a, i), comb(n1, i))*R(comb(b, j), comb(n2, j)) for (i, j), c in co.items() if i <= a and j <= b)
        assert val > 0
        terms.append(f"{lit(val*comb(n1, a)*comb(n2, b))} * (s ^ {a} * (1 - s) ^ {n1-a}) * (w ^ {b} * (1 - w) ^ {n2-b})")
Ebern = " +\n      ".join(terms)

# endpoint cell
z = sp.expand(X*(V + X*W))
P8 = sum((-1)**(j+1)*z**j/j for j in range(1, 9))
P = sp.expand(P8 - K*X*(R(171, 40) - R(8, 3)*v - R(11, 10)*X))


def bern1(lo, hi):
    Pw = sp.Poly(sp.expand(P.subs(v, lo+(hi-lo)*w)), w)
    n = Pw.degree()
    cs = [Pw.coeff_monomial(w**j) for j in range(n+1)]
    return [sum(R(comb(i, j), comb(n, j))*cs[j] for j in range(i+1)) for i in range(n+1)], n


def split(lo, hi, depth=0):
    b, n = bern1(lo, hi)
    if min(b) > 0:
        return [(lo, hi)]
    assert depth < 6
    mid = (lo+hi)/2
    return split(lo, mid, depth+1) + split(mid, hi, depth+1)


boxes = split(-R(6, 25), R(6, 25))
assert len(boxes) == 2

out = [f'''module

public import Mathlib

/-!
# Bernstein certificates for the moment case of the capped cubic lemma

Paper E, `lem:fqe-capped-cubic`, the moment argument for `x = p - 1/4 ≤ 17/100`
(`renyi_capped_cubic.tex`).  Generated by `gen_cc_cells.py`; every identity `p = Σ b_ij B_i B_j` is checked by `ring`.

`N = 1 + x V + x² W` with `V = A + B v + C v²`, `W = C/4 + T v`, `(A,B,C,T)` the order-`q_s` coefficients.

* `ccE_nonpos` (curvature cell): `N² + N N_xx - N_x² ≤ 0` on `0 ≤ x ≤ 17/100`, `|v| ≤ 6/25` (so `(ln N)_xx ≤ -1`);
* `ccTay_nonneg` (endpoint cell): at `x = 17/100`, the eight-term Taylor minorant of `ln N` beats `r L⁺ x (171/40 - (8/3) v - (11/10) x)`
  for `|v| ≤ 6/25`.
-/

@[expose] public section

namespace FormalResearch.FourQubitEntropy.RenyiFull

/-- `A = 2 q (q-1)` at `q = 1587/1000`. -/
noncomputable def ccA : ℝ := {lit(A)}
/-- `B = (8/3) q (q-1) (q-2)`. -/
noncomputable def ccB : ℝ := {lit(B)}
/-- `C = (8/3) q (q-1) (q-2) (q-3)`. -/
noncomputable def ccC : ℝ := {lit(C)}
/-- `T = (2/3)(q-4) C`. -/
noncomputable def ccT : ℝ := {lit(T)}

/-- `N(x, v) = 1 + x V + x² W`. -/
noncomputable def ccN (x v : ℝ) : ℝ := 1 + x * ((ccA + ccB * v + ccC * v ^ 2) + x * (ccC / 4 + ccT * v))

/-- `∂N/∂x`. -/
noncomputable def ccNx (x v : ℝ) : ℝ := (ccA + ccB * v + ccC * v ^ 2) + 2 * x * (ccC / 4 + ccT * v)

/-- `∂²N/∂x²`. -/
noncomputable def ccNxx (v : ℝ) : ℝ := 2 * (ccC / 4 + ccT * v)

/-- `N² + N N_xx - N_x²`. -/
noncomputable def ccE (x v : ℝ) : ℝ := ccN x v ^ 2 + ccN x v * ccNxx v - ccNx x v ^ 2

set_option maxHeartbeats 4000000 in
theorem ccE_nonpos {{x v : ℝ}} (hx0 : 0 ≤ x) (hx1 : x ≤ {lit(X)}) (hv0 : -(6 / 25 : ℝ) ≤ v)
    (hv1 : v ≤ 6 / 25) : ccE x v ≤ 0 := by
  obtain ⟨s, hs0, hs1, rfl⟩ : ∃ s : ℝ, 0 ≤ s ∧ s ≤ 1 ∧ x = {lit(X)} * s :=
    ⟨x / {lit(X)}, by apply div_nonneg <;> linarith, by rw [div_le_one (by norm_num)]; linarith, by field_simp⟩
  obtain ⟨w, hw0, hw1, rfl⟩ : ∃ w : ℝ, 0 ≤ w ∧ w ≤ 1 ∧ v = -(6 / 25 : ℝ) + (12 / 25 : ℝ) * w :=
    ⟨(v + 6 / 25) / (12 / 25), by apply div_nonneg <;> linarith, by rw [div_le_one (by norm_num)]; linarith,
      by field_simp; ring⟩
  have h1 : 0 ≤ 1 - s := by linarith
  have h2 : 0 ≤ 1 - w := by linarith
  have key : -ccE ({lit(X)} * s) (-(6 / 25 : ℝ) + (12 / 25 : ℝ) * w) =
      {Ebern} := by
    unfold ccE ccN ccNx ccNxx ccA ccB ccC ccT; ring
  have : 0 ≤ -ccE ({lit(X)} * s) (-(6 / 25 : ℝ) + (12 / 25 : ℝ) * w) := by rw [key]; positivity
  linarith

/-- The eight-term Taylor minorant of `ln(1+z)` at `x = 17/100`, minus the target. -/
noncomputable def ccTay (v : ℝ) : ℝ :=
  (ccTz v) - (ccTz v) ^ 2 / 2 + (ccTz v) ^ 3 / 3 - (ccTz v) ^ 4 / 4 + (ccTz v) ^ 5 / 5 - (ccTz v) ^ 6 / 6
    + (ccTz v) ^ 7 / 7 - (ccTz v) ^ 8 / 8 - {lit(K)} * ({lit(X)} * (171 / 40 - 8 / 3 * v - 11 / 10 * {lit(X)}))
''']
out[0] = out[0].replace("/-- The eight-term", "/-- The eight-term")
# ccTz must be defined before ccTay: insert
out[0] = out[0].replace("/-- The eight-term Taylor minorant", f"""/-- `z = X (V + X W)` at `x = X = 17/100`. -/
noncomputable def ccTz (v : ℝ) : ℝ := {lit(X)} * ((ccA + ccB * v + ccC * v ^ 2) + {lit(X)} * (ccC / 4 + ccT * v))

/-- The eight-term Taylor minorant""")

for idx, (lo, hi) in enumerate(boxes):
    b, n = bern1(lo, hi)
    assert n == 16 and all(c > 0 for c in b)
    terms = " +\n      ".join(f"{lit(b[i]*comb(n, i))} * (w ^ {i} * (1 - w) ^ {n-i})" for i in range(n+1))
    out.append(f'''
set_option maxHeartbeats 4000000 in
theorem ccTay_cell{idx} {{v : ℝ}} (hv0 : {lit(lo)} ≤ v) (hv1 : v ≤ {lit(hi)}) : 0 ≤ ccTay v := by
  obtain ⟨w, hw0, hw1, rfl⟩ : ∃ w : ℝ, 0 ≤ w ∧ w ≤ 1 ∧ v = {lit(lo)} + {lit(hi-lo)} * w :=
    ⟨(v - {lit(lo)}) / {lit(hi-lo)}, by apply div_nonneg <;> linarith, by rw [div_le_one (by norm_num)]; linarith,
      by field_simp; ring⟩
  have h1 : 0 ≤ 1 - w := by linarith
  have key : ccTay ({lit(lo)} + {lit(hi-lo)} * w) =
      {terms} := by
    unfold ccTay ccTz ccA ccB ccC ccT; ring
  rw [key]
  positivity
''')
# weight-bound cell: u^2 ((1-u)(3-2u))^5 <= 1 on [0, 3/32] (weight bound for the chart B)
uu = sp.symbols('uu')
Pu = sp.expand(1 - uu**2*((1-uu)*(3-2*uu))**5)


def bern1u(lo, hi):
    Pw = sp.Poly(sp.expand(Pu.subs(uu, lo+(hi-lo)*w)), w)
    n = Pw.degree()
    cs = [Pw.coeff_monomial(w**j) for j in range(n+1)]
    return [sum(R(comb(i, j), comb(n, j))*cs[j] for j in range(i+1)) for i in range(n+1)], n


bu, nu_ = bern1u(R(0), R(3, 32))
assert nu_ == 12 and all(c > 0 for c in bu)
termsu = " +\n      ".join(f"{lit(bu[i]*comb(nu_, i))} * (w ^ {i} * (1 - w) ^ {nu_-i})" for i in range(nu_+1))
out.append(f'''
set_option maxHeartbeats 4000000 in
/-- `u² ((1-u)(3-2u))⁵ ≤ 1` on `[0, 3/32]` (weight-bound cell). -/
theorem cc_wB_poly {{u : ℝ}} (h0 : 0 ≤ u) (h1 : u ≤ 3 / 32) : u ^ 2 * ((1 - u) * (3 - 2 * u)) ^ 5 ≤ 1 := by
  obtain ⟨w, hw0, hw1, rfl⟩ : ∃ w : ℝ, 0 ≤ w ∧ w ≤ 1 ∧ u = (3 / 32 : ℝ) * w :=
    ⟨u / (3 / 32), by positivity, by rw [div_le_one (by norm_num)]; exact h1, by field_simp⟩
  have h2 : 0 ≤ 1 - w := by linarith
  have key : 1 - ((3 / 32 : ℝ) * w) ^ 2 * ((1 - (3 / 32 : ℝ) * w) * (3 - 2 * ((3 / 32 : ℝ) * w))) ^ 5 =
      {termsu} := by
    ring
  have : 0 ≤ 1 - ((3 / 32 : ℝ) * w) ^ 2 * ((1 - (3 / 32 : ℝ) * w) * (3 - 2 * ((3 / 32 : ℝ) * w))) ^ 5 := by
    rw [key]; positivity
  linarith
''')
out.append('''
/-- `ccTay ≥ 0` for `|v| ≤ 6/25`. -/
theorem ccTay_nonneg {v : ℝ} (hv0 : -(6 / 25 : ℝ) ≤ v) (hv1 : v ≤ 6 / 25) : 0 ≤ ccTay v := by
  rcases le_total v 0 with h | h
  · exact ccTay_cell0 hv0 h
  · exact ccTay_cell1 h hv1

end FormalResearch.FourQubitEntropy.RenyiFull
''')
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'RenyiFullCCCells.lean'), 'w').write("".join(out))
print("ok")
