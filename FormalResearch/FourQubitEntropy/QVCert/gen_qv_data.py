"""Generate Data.lean: the positive-norm all-state QV certificate (paper E, QVA) as Lean data.

Reads `qv_all_state_certificate.json` (format `qv-positive-norms-v1`, produced and checked by
`verify_qv_all_state_certificate.py` in ResearchNotes/QI/four_qubit_entropy/code) and writes `Data.lean`
next to this file.

    python3 gen_qv_data.py [path/to/qv_all_state_certificate.json]
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).parent
DEFAULT = Path('/home/user/QIprojects/ResearchNotes/QI/four_qubit_entropy/code/qv_all_state_certificate.json')
src = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT
data = json.loads(src.read_text())
assert data['format'] == 'qv-positive-norms-v1'
assert int(data['denominator']) == 48 * 10**21


def lst(xs):
    return '[' + ', '.join(str(x) for x in xs) + ']'


HEADER = '''import Mathlib

/-!
# The positive-norm certificate for (QV): data

Generated by `gen_qv_data.py` from `qv_all_state_certificate.json` (format `qv-positive-norms-v1`); do not edit.
Paper E, `sup_renyi.tex`, `sec:sup-qk`, verifier-map paragraph QVA.

* `hwSupport j`: the highest-weight rows of the six-copy intertwiner for spin `j/2`, each as
  `(negative support, positive support)` of computational-basis indices (bit `k` = copy `k`).
* `blocks`: the 14 blocks `k`. A `Block` stores `a_k` (copies of `z`), the spin tuple `p_k`, the positive integer
  weights `q_ki` and the sparse integer multiplicity vectors `v_ki` (lists of `(multiplicity index, coefficient)`).
  In total 96 covariants `Φ_ki = W_{a_k,p_k} v_ki`.
* `certD = 48 * 10 ^ 21`, the constant `D` of `2 D 𝔇 = Σ_ki q_ki ‖Φ_ki‖²`.
-/

namespace FormalResearch.FourQubitEntropy.QVCert

/-- One block of the certificate. -/
structure Block where
  /-- number of copies of `z` among the six (the other `6 - a` copies are `z̃`) -/
  a : ℕ
  /-- the spin tuple `p_k` (twice the spins, one per qubit slot) -/
  spins : Fin 4 → ℕ
  /-- the positive integer weights `q_ki` -/
  weights : List ℤ
  /-- the sparse integer multiplicity vectors `v_ki`: lists of `(flat multiplicity index, coefficient)` -/
  vecs : List (List (ℕ × ℤ))

/-- Highest-weight rows of the six-copy `SU(2)` intertwiner of spin `j/2` (`j = 0, 2, 4, 6`):
pairs `(negative support, positive support)`. -/
def hwSupport : ℕ → List (List ℕ × List ℕ)'''

out = [HEADER]
hw = data['highest_weight_supports']
cases = []
for j in ('0', '2', '4', '6'):
    items = ', '.join(f'({lst(n)}, {lst(p)})' for n, p in hw[j])
    cases.append(f'  | {j} => [{items}]')
cases.append('  | _ => []')
out.append('\n'.join(cases))
out.append('')
out.append('/-- The constant `D = 48 · 10²¹` of the certificate identity `2 D 𝔇 = Σ_ki q_ki ‖Φ_ki‖²`. -/')
out.append('def certD : ℤ := 48 * 10 ^ 21')
out.append('')
names = []
for idx, b in enumerate(data['blocks']):
    assert len(b['weights']) == len(b['vectors'])
    name = f'block{idx}'
    names.append(name)
    out.append(f'/-- Block {idx}: `a = {b["a"]}`, `p = {tuple(b["spins"])}`, {len(b["weights"])} covariants. -/')
    out.append(f'def {name} : Block where')
    out.append(f'  a := {b["a"]}')
    out.append(f'  spins := ![{", ".join(str(s) for s in b["spins"])}]')
    ws = b['weights']
    out.append('  weights := [' + ',\n    '.join(', '.join(str(x) for x in ws[i:i + 3]) for i in range(0, len(ws), 3)) + ']')
    vs = []
    for v in b['vectors']:
        assert len(v) % 2 == 0
        vs.append('[' + ', '.join(f'({v[t]}, {v[t + 1]})' for t in range(0, len(v), 2)) + ']')
    out.append('  vecs := [' + ',\n    '.join(vs) + ']')
    out.append('')
out.append('/-- The 14 blocks of the certificate. -/')
out.append('def blocks : List Block :=\n  [' + ', '.join(names) + ']')
out.append('')
out.append('end FormalResearch.FourQubitEntropy.QVCert')
(HERE / 'Data.lean').write_text('\n'.join(out) + '\n')
print('wrote', HERE / 'Data.lean', len(names), 'blocks')
