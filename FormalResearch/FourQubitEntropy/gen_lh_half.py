import sympy as s
from sympy import Rational as Q

z = s.symbols('z')
q = Q(1587, 1000); r = q - 1; Llo = Q(693147, 10**6); k = Q(5247, 10000)
B = (1 + 2*z**2)/3; C = (1 + 6*z**2 + 2*z**3)/9
rhs = 72*Q(3, 20)*(1 - C) + 12*Q(159, 100)*(1 - B**2)
K = k + (3 - 3*k - 2*q/3)*z**2 + (2*q/3 - 2 + 2*k)*z**3
P = s.Poly(s.expand(rhs*r*Llo*(1 + K)**3 - (16*q*(q**2 - 1)*(1 - K)*(1 + K)**2 - 16*q**3*(1 - K)**3)), z)
quo, rem = s.div(P, s.Poly(1 - z, z))
assert rem.is_zero
c = [quo.nth(j) for j in range(quo.degree() + 1)]
assert all(x > 0 for x in c)

def lit(f):
    f = Q(f)
    return f"({f.p} / {f.q} : ℝ)" if f.q != 1 else f"({f.p} : ℝ)"

