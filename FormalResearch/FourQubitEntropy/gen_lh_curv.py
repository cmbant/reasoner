#!/usr/bin/env python3
"""Generates RenyiFullLHCurvCells.lean: the three endpoint polynomial inequalities of
lem:fqe-large-head-curvature (renyi_large_head_dual.tex), as exact Bernstein certificates on [0, 3/5].
With q = 1587/1000, r = q - 1, L_lo = 693147/10^6, M_A = 24 gamma 16/9, M_B = 24 gamma 9/4 (gamma = 159/100):
  J(x, y)  <=  M r L_lo (1-x^2)^4 / (16 q)     for y = y_l^A(x), y_l^B(x), y_h(x).
Run: python3 gen_lh_curv.py > RenyiFullLHCurvCells.lean"""
import sympy as s
from sympy import Rational as Q
from math import comb

x = s.symbols('x')
q = Q(1587, 1000); r = q - 1; Llo = Q(693147, 10**6); g = Q(159, 100)
MA = 24 * g * Q(16, 9); MB = 24 * g * Q(9, 4)
kA = Q(61, 80)
W = Q(3, 5)

def J(xx, yy):
    return (6*q**3*yy**4 - 24*q*q*xx*yy**3 + (-8*q**3 + 36*q*xx*xx + 8*q)*yy**2
            + (24*q*q*xx - 24*xx**3 - 24*xx)*yy + 2*q**3 - 36*q*xx*xx - 8*q + 6*xx**4 + 36*xx*xx + 6)

def bern(P):
    n = P.degree(); t = s.symbols('t')
    Pt = s.Poly(s.expand(P.as_expr().subs(x, W*t)), t)
    c = [Pt.coeff_monomial(t**j) for j in range(n + 1)]
    b = [sum(c[j]*Q(comb(i, j), comb(n, j)) for j in range(i + 1)) for i in range(n + 1)]
    return n, [b[i]*comb(n, i)/W**n for i in range(n + 1)]

def lit(f):
    f = Q(f)
    return f"({f.p} / {f.q} : ℝ)" if f.q != 1 else f"({f.p} : ℝ)"

def rat(e):  # sympy expr in x -> Lean text with literals
    return str(e)

CASES = [
    ('A', 'lh_poly_A', MA, (1 + x) - kA*(1 - x), (1 + x) + kA*(1 - x),
     "(1 + x) - 61 / 80 * (1 - x)", "(1 + x) + 61 / 80 * (1 - x)"),
    ('B', 'lh_poly_B', MB, (1 + x)**2 - (1 - x), (1 + x)**2 + (1 - x),
     "(1 + x) ^ 2 - (1 - x)", "(1 + x) ^ 2 + (1 - x)"),
    ('H', 'lh_poly_H', MA, (1 + x)**2 - (1 - x)**2/2, (1 + x)**2 + (1 - x)**2/2,
     "(1 + x) ^ 2 - (1 - x) ^ 2 / 2", "(1 + x) ^ 2 + (1 - x) ^ 2 / 2"),
]

def lean_expr(e):
    """sympy -> Lean source (Rational literals as (p/q : ℝ))"""
    e = s.expand(e)
    out = str(e)
    return out

def lean_poly(e):
    # print polynomial in x with rational coefficients
    P = s.Poly(s.expand(e), x)
    terms = []
    for (k,), c in P.terms():
        terms.append(f"{lit(c)} * x ^ {k}" if k else f"{lit(c)}")
    return " + ".join(terms) if terms else "0"

def main():
    print("""module

public import FormalResearch.FourQubitEntropy.RenyiFullLHQuasi

/-!
# Large-head curvature: the three endpoint polynomial inequalities (generated by `gen_lh_curv.py`)

`lhJ q x y ≤ M r L_lo (1-x²)⁴/(16 q)` on `[0, 3/5]` at `q = 1587/1000` for the three rational
functions `y = y_l^A, y_l^B, y_h` of `x`; exact Bernstein certificates of degree 12, 16, 16.
-/

@[expose] public section

namespace FormalResearch.FourQubitEntropy.RenyiFull

theorem qS_eq_lit : qS = 1587 / 1000 := rfl
""")
    for tag, name, M, Nx, Dx, Nl, Dl in CASES:
        expr = (M*r*Llo*(1 - x**2)**4/(16*q))*Dx**4 - (J(x, Nx/Dx)*Dx**4)
        P = s.Poly(s.cancel(s.expand(expr)), x)
        n, c = bern(P)
        assert all(ci > 0 for ci in c), (tag, [float(ci) for ci in c])
        bern_sum = " + ".join(f"{lit(ci)} * x ^ {i} * ((3 / 5 : ℝ) - x) ^ {n - i}" for i, ci in enumerate(c))
        Ml = lit(M)
        print(f"""theorem {name} {{x : ℝ}} (h0 : 0 ≤ x) (h1 : x ≤ 3 / 5) :
    lhJ qS x (({Nl}) / ({Dl})) ≤
      {Ml} * (587 / 1000 : ℝ) * (693147 / 1000000 : ℝ) * (1 - x ^ 2) ^ 4 / (16 * qS) := by
  have hD : 0 < {Dl} := by nlinarith
  have hB : 0 ≤ (3 / 5 : ℝ) - x := by linarith
  have key : ({Ml} * (587 / 1000 : ℝ) * (693147 / 1000000 : ℝ) * (1 - x ^ 2) ^ 4 / (16 * qS) -
      lhJ qS x (({Nl}) / ({Dl}))) * ({Dl}) ^ 4 =
      {bern_sum} := by
    rw [sub_mul, lhJ_hom _ _ _ _ hD.ne', qS_eq_lit]
    unfold lhJH
    ring
  have hpos : 0 ≤ {bern_sum} := by positivity
  have h4 : 0 < ({Dl}) ^ 4 := by positivity
  by_contra hcon
  push Not at hcon
  have : ({Ml} * (587 / 1000 : ℝ) * (693147 / 1000000 : ℝ) * (1 - x ^ 2) ^ 4 / (16 * qS) -
      lhJ qS x (({Nl}) / ({Dl}))) * ({Dl}) ^ 4 < 0 :=
    mul_neg_of_neg_of_pos (by linarith) h4
  linarith
""")
    print("end FormalResearch.FourQubitEntropy.RenyiFull")

if __name__ == '__main__':
    main()
