#!/usr/bin/env python3
"""Generates RenyiFullSHPoly.lean: the quartic bounds  Q_a(u) <= 8023/4800  on the staircase intervals of
lem:fqe-small-head-dual (small tail), as Bernstein-type positive expansions on subintervals.
Run: python3 gen_sh_poly.py > RenyiFullSHPoly.lean"""
from fractions import Fraction as F
from math import comb
from gen_sh_nodes import NODES

BOUND = F(8023, 4800)
# intervals: (lo, hi, a):  [0,1/100] with a = 0, then [u_i, u_{i+1}] with a = a_i, last ends at 1/4
pts = [u for u, _ in NODES] + [F(1, 4)]
INTERVALS = [(F(0), NODES[0][0], F(0))] + [(pts[i], pts[i + 1], NODES[i][1]) for i in range(len(NODES))]

def polymul(p, q):
    r = [F(0)] * (len(p) + len(q) - 1)
    for i, x in enumerate(p):
        for j, y in enumerate(q):
            r[i + j] += x * y
    return r

def polyadd(p, q):
    n = max(len(p), len(q)); r = [F(0)] * n
    for i, x in enumerate(p): r[i] += x
    for i, x in enumerate(q): r[i] += x
    return r

def scal(c, p): return [c * x for x in p]

def Qpoly(a):
    """coefficients (ascending in u) of Q_a(u) = 1999/1200 + (21/50) d - a d (1-4d) - (159/100) d^2 + c(u) u^2"""
    d = [F(0), F(1), F(-1)]
    d2 = polymul(d, d)
    one_m4d = polyadd([F(1)], scal(F(-4), d))
    t = polyadd(polyadd([F(1999, 1200)], scal(F(21, 50), d)), scal(-a, polymul(d, one_m4d)))
    t = polyadd(t, scal(F(-159, 100), d2))
    cu = [F(3, 200), F(37, 50), F(-159, 100)]
    return polyadd(t, polymul(cu, [F(0), F(0), F(1)]))

def shift_poly(p, lo, hi):
    """expansion of p(u) in the Bernstein basis of [lo,hi], degree n: returns Bernstein coefficients b_i
    with p = sum b_i C(n,i) tau^i (1-tau)^(n-i), tau = (u-lo)/(hi-lo)"""
    n = len(p) - 1
    # p(lo + (hi-lo) tau) as polynomial in tau
    w = hi - lo
    q = [F(0)] * (n + 1)
    for k, c in enumerate(p):
        for j in range(k + 1):
            q[j] += c * comb(k, j) * lo ** (k - j) * w ** j
    # power -> Bernstein: b_i = sum_{j<=i} q_j C(i,j)/C(n,j)
    return [sum(q[j] * F(comb(i, j), comb(n, j)) for j in range(i + 1)) for i in range(n + 1)]

def split(lo, hi, a, depth=0):
    p = polyadd([BOUND], scal(F(-1), Qpoly(a)))
    n = len(p) - 1
    b = shift_poly(p, lo, hi)
    if all(x > 0 for x in b):
        return [(lo, hi, a, b)]
    assert depth < 6, (lo, hi, a)
    mid = (lo + hi) / 2
    return split(lo, mid, a, depth + 1) + split(mid, hi, a, depth + 1)

def lit(f): return f"({f.numerator} / {f.denominator} : ℝ)" if f.denominator != 1 else f"({f.numerator} : ℝ)"

def main():
    print("""module

public import Mathlib

/-!
# Small-head dual: the quartic bounds on the staircase intervals (generated by `gen_sh_poly.py`)

`shQ a u = 1999/1200 + (21/50) d - a d (1-4d) - (159/100) d² + (3/200 + (37/50) u - (159/100) u²) u²`, `d = u(1-u)`,
and `shQ a u ≤ 8023/4800` on each interval; the positive expansions `8023/4800 - shQ = Σ c_i (u-lo)^i (hi-u)^(4-i)`
are found by `nlinarith` from the nonnegative basis terms.
-/

@[expose] public section

namespace FormalResearch.FourQubitEntropy.RenyiFull

/-- The upper bound of `Λ` in the variable `u` after the quartic bound on `h`. -/
noncomputable def shQ (a u : ℝ) : ℝ :=
  1999 / 1200 + 21 / 50 * (u * (1 - u)) - a * (u * (1 - u) * (1 - 4 * (u * (1 - u)))) -
    159 / 100 * (u * (1 - u)) ^ 2 + (3 / 200 + 37 / 50 * u - 159 / 100 * u ^ 2) * u ^ 2
""")
    names = []
    for k, (lo, hi, a) in enumerate(INTERVALS):
        subs = split(lo, hi, a)
        subnames = []
        for j, (l, h, aa, b) in enumerate(subs):
            nm = f"shQ_le_{k}_{j}"
            subnames.append((nm, l, h))
            terms = ", ".join(f"mul_nonneg (pow_nonneg hA {i}) (pow_nonneg hB {4 - i})" for i in range(5))
            print(f"""theorem {nm} {{u : ℝ}} (h1 : {lit(l)} ≤ u) (h2 : u ≤ {lit(h)}) :
    shQ {lit(aa)} u ≤ 8023 / 4800 := by
  have hA : 0 ≤ u - {lit(l)} := by linarith
  have hB : 0 ≤ {lit(h)} - u := by linarith
  unfold shQ
  nlinarith [{terms}]
""")
        # combine
        print(f"theorem shQ_le_{k} {{u : ℝ}} (h1 : {lit(lo)} ≤ u) (h2 : u ≤ {lit(hi)}) :\n    shQ {lit(a)} u ≤ 8023 / 4800 := by")
        # chain of case splits
        def emit(idx, indent):
            if idx == len(subnames) - 1:
                nm, l, h = subnames[idx]
                print(f"{indent}exact {nm} h1 h2")
                return
            nm, l, h = subnames[idx]
            print(f"{indent}by_cases hc{idx} : u ≤ {lit(h)}")
            print(f"{indent}· exact {nm} (by linarith) hc{idx}")
            print(f"{indent}· push Not at hc{idx}")
            emit(idx + 1, indent)
        emit(0, "  ")
        print()
    print("end FormalResearch.FourQubitEntropy.RenyiFull")

if __name__ == "__main__":
    main()
