"""Generate RenyiFullSHLarge cells: RenyiFullSHLargeCells.lean (Paper E, lem:fqe-small-head-dual, large tail).

The polynomial G(x, v) = (V + xW) - x(V+xW)^2/2 + x^2 (V+xW)^3/3 - x^3 (V+xW)^4/4 - r L+ (35/8 - (9/5) v - gamma x)
is nonnegative on 0 <= x <= 3/32, 0 <= v <= 9/50 (one tensor Bernstein cell, bidegree (7,8)).
Run: python3 gen_sh_large.py  (writes RenyiFullSHLargeCells.lean next to this file)."""
import os
import sympy as sp
from sympy import Rational as R, symbols, Poly, binomial
x, v, s, w = symbols('x v s w')
q = R(1587, 1000); r = q - 1
A = 2 * q * r; B = R(8, 3) * q * r * (q - 2); C = R(8, 3) * q * r * (q - 2) * (q - 3); T = R(2, 3) * (q - 4) * C
g = R(159, 100)
Lp = R(693148, 10**6)
V = A + B * v + C * v**2; W = C / 4 + T * v
Z = V + x * W
G = sp.expand(Z - x * Z**2 / 2 + x**2 * Z**3 / 3 - x**3 * Z**4 / 4 - r * Lp * (R(35, 8) - R(9, 5) * v - g * x))
n1, n2 = 7, 8
X0, X1, V0, V1 = R(0), R(3, 32), R(0), R(9, 50)

def lit(q):
    if q < 0:
        return f"(-({-q.p} / {q.q}) : ℝ)" if q.q != 1 else f"(-({-q.p}) : ℝ)"
    return f"({q.p} / {q.q} : ℝ)" if q.q != 1 else f"({q.p} : ℝ)"

def main():
    P = Poly(sp.expand(G.subs({x: X0 + (X1 - X0) * s, v: V0 + (V1 - V0) * w}, simultaneous=True)), s, w)
    co = P.as_dict(); res = {}
    for a in range(n1 + 1):
        for bb in range(n2 + 1):
            tot = 0
            for (i, j), cij in co.items():
                if i <= a and j <= bb:
                    tot += cij * binomial(a, i) * binomial(bb, j) / (binomial(n1, i) * binomial(n2, j))
            res[(a, bb)] = tot * binomial(n1, a) * binomial(n2, bb)
    assert all(val > 0 for val in res.values())
    zz = f"(({lit(A)} + {lit(B)} * v + {lit(C)} * v ^ 2) + x * ({lit(C)} / 4 + {lit(T)} * v))"
    out = []
    out.append(f'''module

public import Mathlib

/-!
# Small-head dual, large tail: the Bernstein certificate (generated by `gen_sh_large.py`)

Paper E, `lem:fqe-small-head-dual`, "Large tail": the polynomial inequality `G(x, v) ≥ 0` on
`0 ≤ x ≤ 3/32`, `0 ≤ v ≤ 9/50`, where `G = Z - xZ²/2 + x²Z³/3 - x³Z⁴/4 - r L⁺ (35/8 - (9/5) v - γ x)`,
`Z = V + xW`, `V = A + Bv + Cv²`, `W = C/4 + Tv` (the order-`q_s` near-uniform coefficients),
`r = q_s - 1`, `L⁺ = 693148/10^6 > ln 2`, `γ = 159/100`.  One tensor Bernstein cell of bidegree `(7, 8)`; the identity
`G = Σ b_ij B_i(s) B_j(w)` is checked by `ring`.
-/

@[expose] public section

namespace FormalResearch.FourQubitEntropy.RenyiFull

/-- The polynomial `G`. -/
noncomputable def shG (x v : ℝ) : ℝ :=
  {zz} - x * {zz} ^ 2 / 2 + x ^ 2 * {zz} ^ 3 / 3 - x ^ 3 * {zz} ^ 4 / 4 -
  ({lit(r * Lp)}) * (35 / 8 - 9 / 5 * v - 159 / 100 * x)
''')
    terms = []
    for a in range(n1 + 1):
        for bb in range(n2 + 1):
            terms.append(f"{lit(res[(a, bb)])} * (s ^ {a} * (1 - s) ^ {n1 - a}) * (w ^ {bb} * (1 - w) ^ {n2 - bb})")
    expr = " +\n      ".join(terms)
    out.append(f'''
set_option maxHeartbeats 8000000 in
set_option maxRecDepth 100000 in
/-- `G ≥ 0` on `0 ≤ x ≤ 3/32`, `0 ≤ v ≤ 9/50`. -/
theorem shG_nonneg {{x v : ℝ}} (hx0 : 0 ≤ x) (hx1 : x ≤ 3 / 32) (hv0 : 0 ≤ v) (hv1 : v ≤ 9 / 50) :
    0 ≤ shG x v := by
  obtain ⟨s, hs0, hs1, rfl⟩ : ∃ s : ℝ, 0 ≤ s ∧ s ≤ 1 ∧ x = (3 / 32 : ℝ) * s :=
    ⟨x / (3 / 32), by positivity, by rw [div_le_one (by norm_num)]; linarith, by field_simp⟩
  obtain ⟨w, hw0, hw1, rfl⟩ : ∃ w : ℝ, 0 ≤ w ∧ w ≤ 1 ∧ v = (9 / 50 : ℝ) * w :=
    ⟨v / (9 / 50), by positivity, by rw [div_le_one (by norm_num)]; linarith, by field_simp⟩
  have h1 : 0 ≤ 1 - s := by linarith
  have h2 : 0 ≤ 1 - w := by linarith
  have key : shG ((3 / 32 : ℝ) * s) ((9 / 50 : ℝ) * w) =
      {expr} := by
    unfold shG; ring
  rw [key]
  positivity

end FormalResearch.FourQubitEntropy.RenyiFull
''')
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'RenyiFullSHLargeCells.lean')
    open(path, 'w').write("".join(out))

if __name__ == '__main__':
    main()
