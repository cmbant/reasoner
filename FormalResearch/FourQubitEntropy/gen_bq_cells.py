cl = []
chain = []
for idx, (lo, hi) in enumerate(boxes):
    last = idx == len(boxes)-1
    ind = "  " * (idx+1)
    call = f"{ind}obtain ⟨w, hw0, hw1, hw⟩ := box {lit(lo)} {lit(hi-lo)} (by norm_num) {'hs0' if idx==0 else 'ha'+str(idx-1)+'.le'} (by {'linarith'})\n{ind}exact bqdM_cell{idx} hw hw0 hw1 ht0 ht1\n"
