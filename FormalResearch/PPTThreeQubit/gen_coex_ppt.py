"""Generator for FormalResearch/PPTThreeQubit/CoexistencePPTData.lean (usage: gen_coex_ppt.py OUTFILE).
Exact arithmetic in Q(omega), omega^2 = -1-omega. Re-derives everything from B, X_BS, X_D."""
from fractions import Fraction as F
import sys

class W:
    def __init__(s,a=0,b=0): s.a=F(a); s.b=F(b)
    def __add__(s,o): o=W.c(o); return W(s.a+o.a,s.b+o.b)
    def __sub__(s,o): o=W.c(o); return W(s.a-o.a,s.b-o.b)
    def __neg__(s): return W(-s.a,-s.b)
    def __mul__(s,o):
        o=W.c(o); return W(s.a*o.a-s.b*o.b, s.a*o.b+s.b*o.a-s.b*o.b)
    __radd__=__add__
    def __rmul__(s,o): return W.c(o)*s
    def conj(s): return W(s.a-s.b,-s.b)
    def iszero(s): return s.a==0 and s.b==0
    @staticmethod
    def c(o): return o if isinstance(o,W) else W(o,0)
    def __eq__(s,o): o=W.c(o); return s.a==o.a and s.b==o.b
w=W(0,1); w2=W(-1,-1)
Bq=[[W() for _ in range(5)] for _ in range(8)]
for j,v in ((0,W(1)),(3,W(-1)),(5,W(-1)),(6,W(-1))): Bq[j][0]=v
Bq[7][1]=W(1)
for j in (1,2,4): Bq[j][2]=W(1)
for j,v in ((3,W(1)),(5,w),(6,w2)): Bq[j][3]=v
for j,v in ((4,W(1)),(2,w),(1,w2)): Bq[j][4]=v
XBS=[[F(x,54375) for x in r] for r in [[1232,0,0,0,0],[0,30493,32,0,0],[0,32,1693,0,0],[0,0,0,3700,0],[0,0,0,0,925]]]
XD=[[F(x,3360) for x in r] for r in [[293,0,0,0,0],[0,577,-105,0,0],[0,-105,273,0,0],[0,0,0,188,0],[0,0,0,0,76]]]
def sig(X):
    return [[sum((Bq[i][a]*W(X[a][b])*Bq[j][b].conj() for a in range(5) for b in range(5)),W()) for j in range(8)] for i in range(8)]
def ptA(S):
    return [[S[4*(j//4)+i%4][4*(i//4)+j%4] for j in range(8)] for i in range(8)]
XG=[[F(x,133) if i==j else F(0) for j,x in enumerate(r)] for i,r in enumerate([[10]*5,[30]*5,[9]*5,[9]*5,[3]*5])]
SBS=sig(XBS); SD=sig(XD); SG=sig(XG)
lam=F(201,200); mu=F(-1,200)
SE=[[SD[i][j]*lam+SBS[i][j]*mu for j in range(8)] for i in range(8)]
XE=[[XD[i][j]*lam+XBS[i][j]*mu for j in range(5)] for i in range(5)]

def ldl(M,c,order_blocks):
    n=len(M)
    M=[[W.c(M[i][j])-(c if i==j else 0) for j in range(n)] for i in range(n)]
    L=[];d=[]
    for blk in order_blocks:
        for pos,k in enumerate(blk):
            dk=M[k][k]
            assert dk.b==0 and dk.a>0,(k,dk.a,dk.b)
            lk=[W() for _ in range(n)]
            lk[k]=W(1)
            for i in blk[pos+1:]:
                lk[i]=M[i][k]*(1/dk.a) if False else M[i][k]*W(1/dk.a)
            for i in range(n):
                for j in range(n):
                    M[i][j]=M[i][j]-lk[i]*lk[j].conj()*W(dk.a)
            L.append(lk); d.append(dk.a)
    for i in range(n):
        for j in range(n): assert M[i][j].iszero(),(i,j)
    return L,d
def check_blocks(P):
    for i in range(8):
        for j in range(8):
            if (bin(i).count('1')%2)!=(bin(j).count('1')%2): assert P[i][j].iszero()
EV=[0,3,5,6]; OD=[1,2,4,7]
def qs(x):
    x=F(x)
    return f"({x.numerator})" if x.denominator==1 else f"({x.numerator}/{x.denominator} : ℚ)"
def qw(p): return f"({qs(p.a)}, {qs(p.b)})"
def tab(M): return "![" + ", ".join("![" + ", ".join(qw(W.c(x)) for x in r) + "]" for r in M) + "]"
